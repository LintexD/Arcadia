    #[test]
    fn test_chunk_compaction_and_gpu_pool_reuse_and_patch_dedup() {
        let palette = MaterialPalette::default();
        let mut chunk = ChunkTree64::default();

        // WHY: Populate chunk with non-trivial nodes and bricks.
        chunk.set_voxels_local(
            &[
                (0, 0, 0, MAT_STONE_DEEP),
                (0, 0, 1, MAT_CRYSTAL_CYAN),
                (16, 16, 16, MAT_STONE_DEEP),
                (16, 16, 17, MAT_CRYSTAL_CYAN),
                (32, 32, 32, MAT_STONE_DEEP),
            ],
            &palette,
        );

        let mut world = WorldMap::from_chunks(UVec3::new(1, 1, 1), vec![chunk], palette);
        world.pending_patches.clear();

        let (initial_n_base, _initial_n_cap, initial_b_base, _initial_b_cap) =
            world.chunk_allocs[0];
        let initial_gpu_nodes_len = world.gpu_nodes.len();
        let initial_gpu_bricks_len = world.gpu_bricks.len();
        assert!(initial_n_base > 0);
        assert!(initial_b_base > 0);

        // WHY: Carve/clear voxels to create orphaned nodes in chunk 0.
        world.clear_voxels_global(&[IVec3::new(32, 32, 32)]);
        let node_count_before_compact = world.chunks[0].nodes.len();

        // WHY: Compact chunk tree directly and verify orphaned nodes are removed.
        world.chunks[0].compact();
        let node_count_after_compact = world.chunks[0].nodes.len();
        assert!(node_count_after_compact <= node_count_before_compact);

        // WHY: Repeatedly set voxels, ensuring capacity reuse without unbounded gpu_nodes growth.
        for i in 0..5 {
            let voxels = [(IVec3::new(0, 0, 2 + i), MAT_STONE_DEEP)];
            world.set_voxels_global(&voxels);
        }

        // WHY: Verify gpu_nodes and gpu_bricks have not experienced unbounded growth.
        assert!(world.gpu_nodes.len() <= initial_gpu_nodes_len + 256);
        assert!(world.gpu_bricks.len() <= initial_gpu_bricks_len + 128);

        // WHY: Deduplicate pending patches for the same chunk.
        world.pending_patches.clear();
        world.sync_dirty_chunk(0);
        world.sync_dirty_chunk(0);
        let chunk_0_patches = world
            .pending_patches
            .iter()
            .filter(|p| p.chunk_flat_idx == 0)
            .count();
        assert_eq!(chunk_0_patches, 1);

        // WHY: Verify free-list reclamation when chunk becomes completely empty.
        world.clear_voxels_global(&[
            IVec3::new(0, 0, 0),
            IVec3::new(0, 0, 1),
            IVec3::new(16, 16, 16),
            IVec3::new(16, 16, 17),
            IVec3::new(0, 0, 2),
            IVec3::new(0, 0, 3),
            IVec3::new(0, 0, 4),
            IVec3::new(0, 0, 5),
            IVec3::new(0, 0, 6),
        ]);
        world.sync_dirty_chunk(0);

        assert!(world.chunks[0].is_empty());
        assert_eq!(world.chunk_allocs[0], (0, 0, 0, 0));
        assert!(!world.free_node_spans.is_empty());

        // WHY: Re-adding a voxel should reuse the reclaimed span rather than growing gpu_nodes tail indefinitely.
        let nodes_len_before_readd = world.gpu_nodes.len();
        world.set_voxels_global(&[(IVec3::new(1, 1, 1), MAT_STONE_DEEP)]);
        assert!(world.chunk_allocs[0].0 > 0);
        assert_eq!(world.gpu_nodes.len(), nodes_len_before_readd);
    }

    #[test]
    fn test_register_dynamic_tree_reuses_free_spans() {
        let palette = MaterialPalette::default();
        let chunk = ChunkTree64::default();
        let mut world = WorldMap::from_chunks(UVec3::new(1, 1, 1), vec![chunk], palette);

        // WHY: Populate free spans to verify register_dynamic_tree reuses them without tail resizing.
        world.free_node_spans.push((100, 20));
        world.free_brick_spans.push((50, 10));
        world.gpu_nodes.resize(120, Node64::empty());
        world.gpu_bricks.resize(60, LeafBrick64::default());

        let mut dynamic_tree = ChunkTree64::default();
        dynamic_tree.set_voxel(0, 0, 0, MAT_STONE_DEEP, &palette);
        dynamic_tree.set_voxel(0, 0, 1, arcadia_core::MAT_CRYSTAL_CYAN, &palette);

        let req_n = dynamic_tree.nodes.len() as u32;
        let req_b = dynamic_tree.bricks.len() as u32;
        assert!(req_n > 0);
        assert!(req_b > 0);

        let initial_gpu_nodes_len = world.gpu_nodes.len();
        let initial_gpu_bricks_len = world.gpu_bricks.len();

        let root_idx = world.register_dynamic_tree(&dynamic_tree);

        // INVARIANT: Node allocation should reuse the free span at 100 rather than growing gpu_nodes.
        assert_eq!(root_idx, 100);
        assert_eq!(world.gpu_nodes.len(), initial_gpu_nodes_len);
        assert_eq!(world.gpu_bricks.len(), initial_gpu_bricks_len);
        assert_eq!(world.free_node_spans, vec![(100 + req_n, 20 - req_n)]);
        assert_eq!(world.free_brick_spans, vec![(50 + req_b, 10 - req_b)]);
    }
