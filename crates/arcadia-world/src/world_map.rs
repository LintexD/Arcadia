    #[test]
    fn test_sync_dirty_chunk_partial_minimal_nodes() {
        let palette = MaterialPalette::default();
        let mut chunk = ChunkTree64::default();
        // WHY: Populate with multiple voxels across different leaf bricks to give chunk non-trivial nodes.
        chunk.set_voxels_local(
            &[
                (0, 0, 0, MAT_STONE_DEEP),
                (4, 0, 0, MAT_STONE_DEEP),
                (8, 0, 0, MAT_STONE_DEEP),
                (12, 0, 0, MAT_STONE_DEEP),
            ],
            &palette,
        );
        let initial_node_count = chunk.nodes.len();
        assert!(initial_node_count > 4);

        let mut world = WorldMap::from_chunks(UVec3::new(1, 1, 1), vec![chunk], palette);
        world.pending_patches.clear();

        let (node_base, _, _brick_base, _) = world.chunk_allocs[0];
        assert!(node_base > 0);

        // WHY: Mutate a voxel in an existing uniform leaf in-place.
        let report =
            world.chunks[0].set_voxels_local_tracked(&[(0, 0, 1, MAT_STONE_DEEP)], &world.palette);
        assert!(!report.had_structural_growth);
        assert!(report.has_dirty_nodes());
        assert!(!report.has_dirty_bricks());

        // WHY: Execute minimal fast path sync.
        world.sync_dirty_chunk_partial(0, &report);
        assert_eq!(world.pending_patches.len(), 1);

        let patch = &world.pending_patches[0];
        assert_eq!(patch.chunk_flat_idx, 0);
        assert_eq!(patch.new_root_node_idx, node_base);
        assert_eq!(patch.node_offset, node_base + report.min_dirty_node as u32);
        assert_eq!(
            patch.nodes.len(),
            report.max_dirty_node - report.min_dirty_node + 1
        );
        // WHY: Minimal slice check: patch.nodes.len() should be less than or equal to initial_node_count.
        assert!(patch.nodes.len() <= initial_node_count);
        // WHY: Zero bricks uploaded because this leaf is uniform.
        assert!(patch.bricks.is_empty());
        assert_eq!(patch.brick_offset, 0);

        // WHY: Verify gpu_nodes matches patch.
        let slice_start = patch.node_offset as usize;
        let slice_end = slice_start + patch.nodes.len();
        assert_eq!(&world.gpu_nodes[slice_start..slice_end], &patch.nodes[..]);
    }

