    #[test]
    fn test_sync_dirty_chunk_partial_structural_growth_within_capacity() {
        let palette = MaterialPalette::default();
        let mut world =
            WorldMap::from_chunks(UVec3::new(1, 1, 1), vec![ChunkTree64::default()], palette);

        // WHY: Initialize chunk with voxels in multiple regions and sync with slack capacity >= 128.
        world.chunks[0].set_voxels_local(
            &[(0, 0, 0, MAT_STONE_DEEP), (48, 48, 48, MAT_STONE_DEEP)],
            &world.palette,
        );
        world.sync_dirty_chunk(0);
        world.pending_patches.clear();

        let (node_base, node_cap, _brick_base, _brick_cap) = world.chunk_allocs[0];
        assert!(node_base > 0);
        assert!(node_cap >= 128);

        // WHY: Adding a voxel in an unallocated sub-branch causes structural growth, but fits capacity.
        let report =
            world.chunks[0].set_voxels_local_tracked(&[(0, 0, 4, MAT_STONE_DEEP)], &world.palette);
        assert!(report.had_structural_growth);
        assert!(world.chunks[0].nodes.len() as u32 <= node_cap);

        world.sync_dirty_chunk_partial(0, &report);
        assert_eq!(world.pending_patches.len(), 1);

        let patch = &world.pending_patches[0];
        assert_eq!(patch.new_root_node_idx, node_base);
        // WHY: Partial sync uploads dirty node range covering growth within capacity.
        assert_eq!(
            patch.nodes.len(),
            report.max_dirty_node - report.min_dirty_node + 1
        );
    }

